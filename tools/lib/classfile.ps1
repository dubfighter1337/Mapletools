# Shared by the importers: writes data/classes/<id>.js and registers it in data/classes/index.js.

$Utf8NoBom = New-Object Text.UTF8Encoding $false

function Js([string]$s) { '"' + ($s -replace '\\', '\\' -replace '"', '\"' -replace "`r?`n", '\n') + '"' }
function Slug([string]$s) { ($s.ToLower() -replace "[^a-z0-9]+", '-').Trim('-') }

# $Data: @{ nodes; orders; version; note }. Nodes are ordered dictionaries with any of:
# id, name, short, nameKo, group, role, min, max, x, y, icon, cost (table name), costs (per level).
function Write-ClassFile {
  param([string]$Root, [string]$Id, [string]$Name, [string]$System, [string]$Category, $Data, [string]$From, [string]$Tool)
  $L = New-Object System.Collections.Generic.List[string]
  $L.Add("// $Name - generated by $Tool on $(Get-Date -Format yyyy-MM-dd).")
  $L.Add("// Safe to edit by hand; see README.md (""Adding or changing data"").")
  $L.Add('MapleData.addClass({')
  $L.Add("  id: $(Js $Id),")
  $L.Add("  name: $(Js $Name),")
  $L.Add("  system: $(Js $System),")
  if ($Category) { $L.Add("  category: $(Js $Category),") }
  $L.Add("  dataVersion: $(Js $Data.version),")
  if ($Data.note) { $L.Add("  dataNote: $(Js $Data.note),") }
  $L.Add("  importedFrom: $(Js $From),")
  $L.Add("  importedOn: $(Js (Get-Date -Format yyyy-MM-dd)),")
  $L.Add('  nodes: [')
  foreach ($n in $Data.nodes) {
    $parts = @("id: $(Js $n.id)", "name: $(Js $n.name)")
    if ($n.Contains('short') -and $n.short -and $n.short -ne $n.name) { $parts += "short: $(Js $n.short)" }
    if ($n.Contains('nameKo') -and $n.nameKo) { $parts += "nameKo: $(Js $n.nameKo)" }
    $parts += "group: $(Js $n.group)"
    if ($n.Contains('role') -and $n.role) { $parts += "role: $(Js $n.role)" }
    if ($n.min) { $parts += "min: $($n.min)" }
    $parts += "max: $($n.max)"
    if ($n.Contains('x')) { $parts += "x: $($n.x)"; $parts += "y: $($n.y)" }
    if ($n.icon) { $parts += "icon: $(Js $n.icon)" }
    if ($n.Contains('cost') -and $n.cost) { $parts += "cost: $(Js $n.cost)" }
    if ($n.Contains('costs') -and $n.costs) { $parts += 'costs: [' + (($n.costs | ForEach-Object { "[$($_[0]),$($_[1])]" }) -join ',') + ']' }
    $L.Add('    { ' + ($parts -join ', ') + ' },')
  }
  $L.Add('  ],')
  $L.Add('  // Each step: [node id, target level] or [node id, target level, "note"]. Listed in upgrade order.')
  $L.Add('  orders: [')
  foreach ($o in $Data.orders) {
    $L.Add("    { id: $(Js $o.id), name: $(Js $o.name), steps: [")
    $chunk = @()
    foreach ($s in $o.steps) {
      if ($s.Count -ge 3) {
        if ($chunk.Count) { $L.Add('      ' + ($chunk -join ', ') + ','); $chunk = @() }
        $L.Add("      [$(Js $s[0]),$($s[1]),$(Js $s[2])],")
      } else {
        $chunk += "[$(Js $s[0]),$($s[1])]"
        if ($chunk.Count -ge 8) { $L.Add('      ' + ($chunk -join ', ') + ','); $chunk = @() }
      }
    }
    if ($chunk.Count) { $L.Add('      ' + ($chunk -join ', ') + ',') }
    $L.Add('    ] },')
  }
  $L.Add('  ],')
  $L.Add('});')
  $path = Join-Path $Root "data/classes/$Id.js"
  New-Item -ItemType Directory -Force (Split-Path $path) | Out-Null
  [IO.File]::WriteAllText($path, ($L -join "`n") + "`n", $Utf8NoBom)
  return $path
}

# One line for data/classes/index.js, read from the class file: id, name, category, system and an
# emblem icon (the Origin skill), so pages can list classes without loading every class file.
function Get-ClassListLine([string]$Root, [string]$Id) {
  $text = [IO.File]::ReadAllText((Join-Path $Root "data/classes/$Id.js"), [Text.Encoding]::UTF8)
  $field = { param($k) $m = [regex]::Match($text, "(?m)^\s*$k\:\s*""([^""]*)"""); if ($m.Success) { $m.Groups[1].Value } else { '' } }
  $icon = [regex]::Match($text, '\{ id: "[^"]+", name: "[^"]+"[^\n]*role: "Origin"[^\n]*icon: "([^"]+)"').Groups[1].Value
  if (-not $icon) { $icon = [regex]::Match($text, '\{ id: "origin", [^\n]*icon: "([^"]+)"').Groups[1].Value }
  $parts = @("id: $(Js $Id)", "name: $(Js (& $field 'name'))", "category: $(Js (& $field 'category'))", "system: $(Js (& $field 'system'))")
  if ($icon) { $parts += "icon: $(Js $icon)" }
  return '  { ' + ($parts -join ', ') + ' },'
}

# Adds or refreshes the class in MapleData.classList in data/classes/index.js (keeps everything else).
function Register-Class {
  param([string]$Root, [string]$Id)
  $path = Join-Path $Root 'data/classes/index.js'
  if (-not (Test-Path $path)) {
    $text = "// Every class (data/classes/<id>.js), with what pages need to list it. The importers keep this up to date.`n" +
            "MapleData.classList = [`n];`n" +
            "MapleData.classFiles = MapleData.classList.map((c) => c.id);`n" +
            "// Classes shown as tabs until a viewer picks their own (at most 15).`n" +
            "MapleData.defaultPinned = [];`n"
    [IO.File]::WriteAllText($path, $text, $Utf8NoBom)
  }
  $lines = New-Object System.Collections.Generic.List[string]
  foreach ($l in [IO.File]::ReadAllLines($path, [Text.Encoding]::UTF8)) { $lines.Add($l) }
  $line = Get-ClassListLine $Root $Id
  $idx = -1; $end = -1; $inList = $false
  for ($i = 0; $i -lt $lines.Count; $i++) {
    if ($lines[$i] -match '^MapleData\.classList = \[') { $inList = $true; continue }
    if ($inList -and $lines[$i] -match '^\];') { $end = $i; break }
    if ($inList -and $lines[$i] -match "^\s*\{ id: ""$([regex]::Escape($Id))""") { $idx = $i }
  }
  if ($idx -ge 0) { $lines[$idx] = $line } elseif ($end -ge 0) { $lines.Insert($end, $line) } else { throw "No MapleData.classList in $path" }
  [IO.File]::WriteAllText($path, ($lines -join "`n") + "`n", $Utf8NoBom)
}
